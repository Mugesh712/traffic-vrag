"""M16 — LaTeX-ready table emission.

A table whose numbers could not be computed renders as an explicit
"not available" note stating *why*, never as zeros or dashes. A zero in a
results table reads as a measurement ("the system scored 0") when the truth is
"this was never measured", and that distinction is the difference between an
honest paper and a retracted one.
"""
from __future__ import annotations

from dataclasses import dataclass


def _escape(value: object) -> str:
    text = str(value)
    for char, replacement in (
        ("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("$", r"\$"),
        ("#", r"\#"), ("_", r"\_"), ("{", r"\{"), ("}", r"\}"),
        ("~", r"\textasciitilde{}"), ("^", r"\textasciicircum{}"),
    ):
        text = text.replace(char, replacement)
    return text


@dataclass
class Table:
    caption: str
    label: str
    columns: list[str]
    rows: list[dict]
    unavailable_reason: str | None = None

    def to_latex(self) -> str:
        if self.unavailable_reason:
            return (
                f"% {self.caption}\n"
                f"% NOT AVAILABLE: {self.unavailable_reason}\n"
                f"\\begin{{table}}[h]\n\\centering\n"
                f"\\caption{{{_escape(self.caption)}}}\n"
                f"\\label{{{self.label}}}\n"
                f"\\textit{{Not available: {_escape(self.unavailable_reason)}}}\n"
                f"\\end{{table}}\n"
            )

        alignment = "l" + "r" * (len(self.columns) - 1)
        lines = [
            f"% {self.caption}",
            "\\begin{table}[h]",
            "\\centering",
            f"\\caption{{{_escape(self.caption)}}}",
            f"\\label{{{self.label}}}",
            f"\\begin{{tabular}}{{{alignment}}}",
            "\\toprule",
            " & ".join(_escape(c) for c in self.columns) + " \\\\",
            "\\midrule",
        ]
        for row in self.rows:
            lines.append(" & ".join(_escape(row.get(c, "")) for c in self.columns) + " \\\\")
        lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
        return "\n".join(lines)

    def to_text(self) -> str:
        """Plain-text rendering for the terminal."""
        if self.unavailable_reason:
            return f"{self.caption}\n  NOT AVAILABLE: {self.unavailable_reason}\n"
        widths = {
            c: max(len(str(c)), *(len(str(r.get(c, ""))) for r in self.rows)) if self.rows else len(str(c))
            for c in self.columns
        }
        lines = [self.caption, "  " + "  ".join(str(c).ljust(widths[c]) for c in self.columns)]
        lines.append("  " + "  ".join("-" * widths[c] for c in self.columns))
        for row in self.rows:
            lines.append("  " + "  ".join(str(row.get(c, "")).ljust(widths[c]) for c in self.columns))
        return "\n".join(lines) + "\n"


def render_document(tables: list[Table], video_id: str) -> str:
    header = (
        "% Generated by src/eval (M16). Do not edit by hand.\n"
        f"% Video: {video_id}\n"
        "% Requires: \\usepackage{booktabs}\n\n"
    )
    return header + "\n".join(t.to_latex() for t in tables)


def render_text(tables: list[Table]) -> str:
    return "\n".join(t.to_text() for t in tables)
